using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Text;

namespace PluginManifestGenerator;

[Generator]
public class PluginManifestGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var pluginCandidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) =>
                    node is ClassDeclarationSyntax cds && cds.BaseList != null,
                transform: static (ctx, _) =>
                {
                    var classDecl = (ClassDeclarationSyntax)ctx.Node;
                    var symbol = ctx.SemanticModel.GetDeclaredSymbol(classDecl) as INamedTypeSymbol;
                    // Return both symbol and semantic model
                    return (symbol, ctx.SemanticModel);
                })
            .Where(tuple => tuple.symbol is not null && InheritsFromPluginBase(tuple.symbol!));

        context.RegisterSourceOutput(pluginCandidates, (spc, tuple) =>
        {
            var (symbol, semanticModel) = tuple;
            var manifest = PluginManifestBuilder.BuildManifest(symbol!, semanticModel);
            var yaml = ManifestSourceEmitter.EmitYaml(manifest);

            var source = $@"// <auto-generated/>
namespace GeneratedPluginManifests
{{
    public static class {manifest.PluginClassName}_Manifest
    {{
        public static string Yaml => @""{yaml.Replace("\"", "\"\"")}"";
    }}
}}";
            spc.AddSource($"{manifest.PluginClassName}_Manifest.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static bool InheritsFromPluginBase(INamedTypeSymbol symbol)
    {
        var current = symbol.BaseType;
        while (current != null)
        {
            if (current.Name == "PluginBase")
                return true;
            current = current.BaseType;
        }
        return false;
    }
}
